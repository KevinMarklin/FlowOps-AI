// Seed writes only into a newly created directory, never over existing articles.
// Callers remove this directory if their workspace transaction fails.
func (t OrganizationTemplate) Seed(dir string) (err error) {
	if err := os.Mkdir(dir, 0700); err != nil {
		return err
	}
	defer func() {
		if err != nil {
			_ = os.RemoveAll(dir)
		}
	}()
	for _, d := range t.Documents {
		body := fmt.Sprintf("---\ndepartment: %s\nkeywords: %s\n---\n# %s\n\nСтартовый шаблон. Требует адаптации под правила вашей организации.\n\n%s\n", d.Department, d.Keywords, d.Title, d.Content)
		if err := os.WriteFile(filepath.Join(dir, d.Slug+".md"), []byte(body), 0600); err != nil {
			return err
		}
	}
	return nil
}
